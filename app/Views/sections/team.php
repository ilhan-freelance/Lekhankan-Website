<script>
  function switchTeamTab(tabId, btn) {
    document.querySelectorAll('.team-tab-pane').forEach(p => p.classList.add('hidden'));
    document.getElementById(tabId).classList.remove('hidden');
    document.querySelectorAll('.team-tab-btn').forEach(b => {
      b.classList.remove('bg-saffron-500', 'text-indigo-900', 'shadow-lg');
      b.classList.add('bg-white/10', 'text-slate-300');
    });
    btn.classList.remove('bg-white/10', 'text-slate-300');
    btn.classList.add('bg-saffron-500', 'text-indigo-900', 'shadow-lg');
  }
</script>
